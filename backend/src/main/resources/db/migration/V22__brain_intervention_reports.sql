CREATE TABLE IF NOT EXISTS brain_intervention_reports (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  user_name VARCHAR(255) NULL,
  doctor_id CHAR(36) NULL,
  report_type VARCHAR(64) NOT NULL DEFAULT 'brain_intervention',
  task_type VARCHAR(64) NOT NULL DEFAULT 'neurofeedback',
  task_name VARCHAR(255) NOT NULL,
  protocol_key VARCHAR(96) NULL,
  started_at DATETIME(3) NOT NULL,
  ended_at DATETIME(3) NULL,
  duration_sec INT NOT NULL DEFAULT 0,
  status ENUM('completed','interrupted','invalid') NOT NULL DEFAULT 'completed',
  main_score DECIMAL(10,2) NULL,
  avg_score DECIMAL(10,2) NULL,
  max_score DECIMAL(10,2) NULL,
  stable_duration_sec INT NULL,
  signal_quality_avg DECIMAL(10,4) NULL,
  artifact_ratio DECIMAL(10,4) NULL,
  summary TEXT NULL,
  suggestion TEXT NULL,
  metrics_json JSON NULL,
  curve_json JSON NULL,
  config_json JSON NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  KEY idx_brain_reports_user_time (user_id, started_at),
  KEY idx_brain_reports_doctor_time (doctor_id, started_at),
  KEY idx_brain_reports_type_time (report_type, task_type, protocol_key, started_at),
  CONSTRAINT fk_brain_reports_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_brain_reports_doctor FOREIGN KEY (doctor_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
